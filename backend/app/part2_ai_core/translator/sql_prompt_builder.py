from app.part1_data_security.integration.schema_inspector import get_database_schema_info


def build_sql_prompt(user_query: str, chat_history: list = None) -> str:
    """
    สร้าง Prompt สำหรับแปลงภาษาธรรมชาติเป็น SQL
    รวมทั้งคำถาม, โครงสร้างตาราง (Schema) และประวัติการสนทนา
    """
    schema = get_database_schema_info()

    history_lines = []
    if chat_history:
        for msg in chat_history[-5:]:
            if isinstance(msg, dict):
                role = msg.get("role", "user")
                text_content = msg.get("text") or msg.get("content") or ""
                if text_content:
                    history_lines.append(f"- {role}: {text_content}")
            elif hasattr(msg, "content"):
                role = getattr(msg, "role", "user")
                history_lines.append(f"- {role}: {msg.content}")

    history_str = ""
    if history_lines:
        history_str = "\nประวัติการสนทนาก่อนหน้า:\n" + "\n".join(history_lines)

    prompt = f"""คุณคือผู้เชี่ยวชาญด้าน SQLite Database ขั้นสูง
นี่คือโครงสร้างตารางและความสัมพันธ์ในฐานข้อมูลปัจจุบัน:
{schema}
{history_str}

คำถามจากผู้ใช้: "{user_query}"

ข้อบังคับอย่างเคร่งครัดในการสร้างคำสั่ง SQL:
1. คืนค่าเฉพาะคำสั่ง SQL เพียวๆ เท่านั้น ห้ามมีคำอธิบาย ห้ามมีข้อความนำหน้า ห้ามใส่ markdown block ครอบ
2. **การเลือกคอลัมน์ให้ครบถ้วน (Comprehensive SELECT)**:
   - หากมีการกรองเงื่อนไข `WHERE` บนคอลัมน์ใด (เช่น `WHERE period_of_inv LIKE '%น้อยกว่า 30 วัน%'` หรือ `WHERE year = 2558`):
     **ต้อง SELECT คอลัมน์ที่กรองนั้น (เช่น `period_of_inv`, `year`) และคอลัมน์ตัวเลข/หน่วย (`value`, `unit`) ออกมาในผลลัพธ์ด้วยเสมอ** เพื่อให้ระบบสรุปรายงานและสร้างกราฟได้อย่างสมบูรณ์
   - หากคอลัมน์เป็นข้อความระบุช่วงเวลา เช่น `period_of_inv`, `period`: ให้ใช้เงื่อนไขแบบข้อความ `WHERE period_of_inv LIKE '%น้อยกว่า 30 วัน%'` (ห้าม CAST เป็นตัวเลข)
3. **การให้ความสำคัญกับตารางที่ผู้ใช้อัปโหลดเข้ามา (User Uploaded Tables Priority - สำคัญสูงสุด)**:
   - หากใน Schema มีส่วน "=== ตารางข้อมูลที่ผู้ใช้อัปโหลดเข้ามา ===":
     **ให้ถือว่าผู้ใช้ต้องการสอบถามและวิเคราะห์ข้อมูลจากตารางที่อัปโหลดเข้ามานี้เป็นหลักเสมอ**
   - เมื่อผู้ใช้ถามคำถามกว้างๆ หรือถามภาพรวม เช่น "แสดงโครงสร้างและรายชื่อข้อมูลที่มีทั้งหมด", "แสดงข้อมูลทั้งหมด", "แสดงรายการข้อมูล", "สรุปข้อมูลในชุดข้อมูล":
     - คำว่า "รายชื่อข้อมูล" หรือ "ข้อมูลที่มี" ในภาษาไทย หมายถึง "รายการข้อมูลในตารางที่อัปโหลด" ไม่ได้หมายถึง "รายชื่อลูกค้า" (ห้ามไป SELECT customers เด็ดขาด!)
     - **ต้องสร้าง SQL ดึงข้อมูลจากตารางที่ผู้ใช้อัปโหลดเข้ามา** เช่น `SELECT * FROM "ชื่อตารางที่อัปโหลด" LIMIT 20;`
   - **ห้ามไปดึงข้อมูลจากตาราง mock data (customers, products, orders) มาตอบเด็ดขาด** เมื่อมีตารางที่ผู้ใช้อัปโหลดอยู่ในฐานข้อมูล เว้นแต่ผู้ใช้จะเอ่ยคำว่า "ลูกค้า", "คำสั่งซื้อ", "สินค้า" ออกมาอย่างชัดเจน
   - **กรณีไม่มีตารางที่อัปโหลดอยู่ใน Schema (มีเฉพาะ Mock Tables)**:
     - หากผู้ใช้เอ่ยถามถึง "ชุดข้อมูลที่อัปโหลด" หรือ "ไฟล์ที่อัปโหลด": ห้ามนำตาราง mock data (customers, products, orders) มาสวมรอยตอบเป็นอันขาด ให้คืนค่าข้อความว่าไม่พบตารางที่อัปโหลด
4. หากต้องแสดงข้อมูลที่เกี่ยวข้อง เช่น ชื่อสินค้า หรือ ชื่อลูกค้า ในตาราง mock ให้ใช้ JOIN เพื่อดึง name มาแสดงเสมอ ไม่แสดงเฉพาะ foreign key id
5. ใช้เฉพาะชื่อตารางและชื่อคอลัมน์ที่ระบุใน Schema เท่านั้น หากชื่อตารางมีภาษาไทยให้ครอบด้วยเครื่องหมาย double quotes เสมอ เช่น `FROM "ชื่อตาราง"`
6. คำสั่ง SQL ต้องขึ้นต้นด้วย SELECT หรือ WITH เท่านั้น
7. ไม่ใช้คำสั่ง DDL หรือ DML เช่น DROP, DELETE, INSERT, UPDATE เด็ดขาด
8. **คำสั่งประเภท "แจกแจง", "จัดกลุ่ม", "แบ่งตาม", "ตามแต่ละ..." (Categorical Breakdown / Grouping)**:
   - หากผู้ใช้ขอให้ "แจกแจง", "จัดกลุ่มตามหมวดหมู่", "นับจำนวนตามแต่ละ..." หรือ "แบ่งตาม...":
     **ต้องสร้างคำสั่ง SQL ที่ใช้ GROUP BY คอลัมน์หมวดหมู่นั้นๆ พร้อมกับ COUNT(*) เสมอ (ห้ามใช้ SELECT * ทั้งตาราง)**
     เช่น `SELECT "อำเภอ", COUNT(*) AS "จำนวนรายการ" FROM "ชื่อตาราง" GROUP BY "อำเภอ" ORDER BY "จำนวนรายการ" DESC;`
   - หากผู้ใช้ถามคำถามแบบกว้างๆ เช่น "แจกแจงจำนวนรายการตามแต่ละหมวดหมู่ใน [ตาราง]":
     ให้ตรวจสอบรายชื่อคอลัมน์ใน Schema ของตารางนั้น แล้วเลือกคอลัมน์ที่เป็นข้อความ/มิติหมวดหมู่ที่เหมาะสมที่สุด (เช่น "อำเภอ", "ประเภท", "กลุ่ม", "หมวดหมู่", "สถานะ") มาทำ GROUP BY และเรียงลำดับจากมากไปน้อย
"""
    return prompt
